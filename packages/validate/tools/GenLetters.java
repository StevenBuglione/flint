// Writes packages/validate/source/flint/validate/internal/letters.d: the code point ranges of Unicode general
// category L (Lu, Ll, Lt, Lm, Lo) as JDK 21's Character.getType reports them, which is what java.util.regex's
// \p{L} matches (and so what Hibernate Validator's @Pattern accepts).
//   javac GenLetters.java && java GenLetters ../source/flint/validate/internal/letters.d
import java.nio.file.Files;
import java.nio.file.Path;

public class GenLetters {
    static boolean letter(int cp) {
        switch (Character.getType(cp)) {
            case Character.UPPERCASE_LETTER: case Character.LOWERCASE_LETTER: case Character.TITLECASE_LETTER:
            case Character.MODIFIER_LETTER: case Character.OTHER_LETTER: return true;
            default: return false;
        }
    }

    public static void main(String[] args) throws Exception {
        StringBuilder rows = new StringBuilder();
        int count = 0, column = 0;
        for (int cp = 0x80; cp <= Character.MAX_CODE_POINT; cp++) {
            if (!letter(cp)) continue;
            int end = cp;
            while (end + 1 <= Character.MAX_CODE_POINT && letter(end + 1)) end++;
            String item = String.format("[0x%X, 0x%X],", cp, end);
            if (column + item.length() + 1 > 116) { rows.append("\n"); column = 0; }
            rows.append(column == 0 ? "    " : " ").append(item);
            column += item.length() + (column == 0 ? 4 : 1);
            count++;
            cp = end;
        }
        String text = "// Generated by packages/validate/tools/GenLetters.java from JDK " + System.getProperty("java.version")
            + " (Unicode general category L,\n// as java.util.regex's \\p{L} matches it). Do not edit.\n"
            + "module flint.validate.internal.letters;\n\n@safe:\n\n"
            + "/// The non-ASCII ranges of category L, first and last code point, sorted: " + count + " ranges.\n"
            + "package(flint.validate) immutable uint[2][] letterRanges = [\n" + rows + "\n];\n\n"
            + "/// Whether `cp` is a Unicode letter (`\\p{L}`).\n"
            + "package(flint.validate) bool isUnicodeLetter(uint cp) pure nothrow @nogc\n{\n"
            + "    if (cp < 0x80)\n        return (cp | 0x20) >= 'a' && (cp | 0x20) <= 'z';\n"
            + "    size_t low, high = letterRanges.length;\n"
            + "    while (low < high)\n    {\n        const middle = (low + high) / 2;\n"
            + "        if (cp < letterRanges[middle][0])\n            high = middle;\n"
            + "        else if (cp > letterRanges[middle][1])\n            low = middle + 1;\n"
            + "        else\n            return true;\n    }\n    return false;\n}\n";
        Files.writeString(Path.of(args[0]), text);
    }
}
