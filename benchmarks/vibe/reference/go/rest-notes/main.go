// Command notes serves a notes REST API with registration, login and bearer tokens, stored in SQLite.
package main

import (
	"context"
	"errors"
	"log"
	"net/http"
	"os"
	"os/signal"
	"syscall"
	"time"
)

func main() {
	port := getenv("PORT", "8080")
	db, err := OpenDatabase(getenv("DATABASE_PATH", "notes.db"))
	if err != nil {
		log.Fatal(err)
	}
	defer db.Close()

	server := &http.Server{Addr: "127.0.0.1:" + port, Handler: Routes(&Store{db}), ReadHeaderTimeout: 10 * time.Second}
	ctx, stop := signal.NotifyContext(context.Background(), syscall.SIGTERM, syscall.SIGINT)
	defer stop()
	go func() {
		<-ctx.Done()
		shutdown, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		defer cancel()
		server.Shutdown(shutdown)
	}()
	log.Printf("listening on %s", server.Addr)
	if err := server.ListenAndServe(); !errors.Is(err, http.ErrServerClosed) {
		log.Fatal(err)
	}
}

func getenv(name, fallback string) string {
	if value := os.Getenv(name); value != "" {
		return value
	}
	return fallback
}
