// Regenerate the marked Formatter table with pinned JDK 21, then run repo dfmt.
// java GenFormatterUppercase.java ../source/flint/java/util/internal/formatter_unicode.d
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Locale;

public class GenFormatterUppercase {
    private static final String START = "// BEGIN GENERATED ROOT UPPERCASE EXPANSIONS\n";
    private static final String END = "// END GENERATED ROOT UPPERCASE EXPANSIONS";

    public static void main(String[] args) throws Exception {
        var index = new ArrayList<Integer>();
        var bytes = new ArrayList<Integer>();
        for (int cp = 0; cp <= Character.MAX_CODE_POINT; ++cp) {
            String source = new String(Character.toChars(cp));
            String simple = new String(Character.toChars(Character.toUpperCase(cp)));
            String upper = source.toUpperCase(Locale.ROOT);
            if (upper.equals(simple)) continue;
            byte[] expansion = upper.getBytes(StandardCharsets.UTF_8);
            if (cp > 0xffff || bytes.size() > 0x1fff || expansion.length > 7)
                throw new IllegalStateException("Expansion does not fit the Formatter index: " + cp);
            index.add((cp << 16) | (bytes.size() << 3) | expansion.length);
            for (byte unit : expansion)
                bytes.add(unit & 0xff);
        }

        var table = new StringBuilder();
        table.append("// Generated by GenFormatterUppercase.java on JDK ")
             .append(Runtime.version()).append(".\n");
        table.append("// Index words store the code point, byte offset and byte length.\n");
        table.append("private immutable uint[").append(index.size()).append("] rootUppercaseIndex = [\n");
        for (int entry : index)
            table.append(String.format(Locale.ROOT, "    0x%08X,\n", entry));
        table.append("];\n\nprivate immutable char[").append(bytes.size()).append("] rootUppercaseBytes = [\n");
        for (int unit : bytes)
            table.append(String.format(Locale.ROOT, "    0x%02X,\n", unit));
        table.append("];\n");

        Path path = Path.of(args[0]);
        String source = Files.readString(path);
        int start = source.indexOf(START);
        int end = source.indexOf(END);
        if (start < 0 || end < start + START.length())
            throw new IllegalArgumentException("Formatter table markers are missing");
        Files.writeString(path, source.substring(0, start + START.length()) + table + source.substring(end));
    }
}
