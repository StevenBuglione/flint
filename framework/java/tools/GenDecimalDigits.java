import java.io.BufferedOutputStream;
import java.util.ArrayList;

class GenDecimalDigits {
    public static void main(String[] args) throws Exception {
        if (Runtime.version().feature() != 21) {
            throw new IllegalStateException("Run with Java SE 21");
        }
        if (args.length == 1 && args[0].equals("--vectors")) {
            var output = new BufferedOutputStream(System.out);
            for (int cp = 0; cp <= Character.MAX_CODE_POINT; ++cp) {
                output.write(Character.digit(cp, 36) + 1);
            }
            output.flush();
            return;
        }
        var starts = new ArrayList<Integer>();
        for (int cp = Character.MIN_SUPPLEMENTARY_CODE_POINT; cp <= Character.MAX_CODE_POINT; ++cp) {
            int value = Character.digit(cp, 10);
            if (value < 0) {
                continue;
            }
            for (int offset = 0; offset < 10; ++offset) {
                if (Character.digit(cp + offset, 10) != offset) {
                    throw new IllegalStateException("Non-consecutive decimal run at U+" + Integer.toHexString(cp));
                }
            }
            starts.add(cp);
            cp += 9;
        }
        System.out.println("// Generated by GenDecimalDigits.java using the Java SE 21 Character API.");
        System.out.println("// Run the generator and format its output with the repository dfmt.");
        System.out.println("module flint.java.lang.internal.data.supplementarydigits;");
        System.out.println();
        System.out.println("@safe:");
        System.out.println();
        System.out.println("package(flint.java.lang) static immutable uint[] decimalStarts = [");
        for (int i = 0; i < starts.size(); ++i) {
            if (i % 8 == 0) {
                System.out.print("    ");
            }
            System.out.printf("0x%x,", starts.get(i));
            System.out.print(i % 8 == 7 || i == starts.size() - 1 ? "\n" : " ");
        }
        System.out.println("];");
    }
}
