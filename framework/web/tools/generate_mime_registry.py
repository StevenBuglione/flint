#!/usr/bin/env python3
"""Generate flint.http.mime_registry from Spring Framework v7.1.0's mime.types."""

import argparse
from hashlib import sha256
from pathlib import Path


PINNED_SHA256 = "90edad013f7d6273ac5772a1661f02c8a35f95a6959d5be8cb87c1b1f81aaa9a"


def emit_registry(source):
    media_types = {}
    extensions = {}
    for line in source.decode("ascii").splitlines():
        if not line or line.startswith("#"):
            continue
        media_type, *suffixes = line.split()
        if not suffixes:
            continue
        index = media_types.setdefault(media_type, len(media_types))
        for suffix in suffixes:
            extensions.setdefault(suffix.lower(), []).append(index)

    header = f"""// Generated by framework/web/tools/generate_mime_registry.py.
// Spring Framework v7.1.0, spring-web/src/main/resources/org/springframework/http/mime.types.
// The pinned mime.types file is in the public domain for unlimited redistribution.
// Input SHA-256: {sha256(source).hexdigest()}
module flint.http.mime_registry;

@safe:
package(flint.http):

struct MimeRegistration
{{
    string extension;
    ushort offset;
    ubyte count;
}}

// dfmt off
immutable string[] registeredMimeTypeNames = [
"""
    lines = [header]
    for name in media_types:
        lines.append(f'    "{name}",\n')
    lines.append("];\n\nimmutable MimeRegistration[] mimeRegistrations = [\n")
    indices = []
    for extension, values in sorted(extensions.items()):
        lines.append(f'    MimeRegistration("{extension}", {len(indices)}, {len(values)}),\n')
        indices.extend(values)
    lines.append("];\n\nimmutable ushort[] registeredMimeTypeIndices = [\n")
    for start in range(0, len(indices), 16):
        lines.append("    " + ", ".join(str(index) for index in indices[start : start + 16]) + ",\n")
    lines.append("];\n// dfmt on\n")
    return "".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mime_types", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--check", action="store_true", help="verify that output matches the pinned input")
    args = parser.parse_args()
    source = args.mime_types.read_bytes()
    if sha256(source).hexdigest() != PINNED_SHA256:
        parser.error("mime.types does not match the Spring Framework v7.1.0 input")
    generated = emit_registry(source)
    if args.check:
        if args.output.read_text(encoding="utf-8") != generated:
            parser.error(f"{args.output} differs from the pinned registry")
    else:
        args.output.write_text(generated, encoding="utf-8")


if __name__ == "__main__":
    main()
