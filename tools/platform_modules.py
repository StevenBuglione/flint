#!/usr/bin/env python3
"""Platform modules (ADR-023 amendment, plan section 7).

A platform module is one repo: a set of flint:* packages that share one tag and resolve by platform version, never
by minimal version selection. `platform.lock` in the flint repo pins every Flint repo; the `flint-dependencies`
bill of materials (boot/dependencies/flint-dependencies.json, as spring-boot-dependencies) pins the coordinated
set of artifacts for applications.

Each repo also takes its slice of the native and peer locks: `policy/lock-partitions.json` lists, per repo, the
native libraries its packages consume (with their dependencies, and the providers of its Flint C shim archive)
and the fixture peers its tests use.

    python3 tools/platform_modules.py --check     # platform.lock covers every repo; the generated files are current
    python3 tools/platform_modules.py --write     # regenerate the bill of materials and the lock partitions
"""
import argparse
import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
from workspace import package_repos, repo_policy  # noqa: E402

LOCK = ROOT / 'platform.lock'
BOM = ROOT / 'boot' / 'dependencies' / 'flint-dependencies.json'
PARTITIONS = ROOT / 'policy' / 'lock-partitions.json'

# Providers of a repo's Flint C shim archive (native/ffi/CMakeLists.txt): the flint repo's flint_ffi_base wraps
# libyaml and utf8proc, so the flint repo carries them even where framework packages consume them too.
SHIM_PROVIDERS = {'flint': ['libyaml', 'utf8proc']}
# Lock consumers that are not packages: a build tool of a package, or a flint tool.
TOOL_CONSUMERS = {'rpc-codegen-build-tool': 'rpc'}


def consumer_repo(consumer, owners):
    if consumer in owners:
        return owners[consumer][0]
    if consumer in TOOL_CONSUMERS:
        return owners[TOOL_CONSUMERS[consumer]][0]
    if consumer.startswith(('tools/', 'apps/flint/')):
        return 'flint'
    raise ValueError(f'lock consumer {consumer!r} is neither a package nor a known tool')


def lock_partitions(root=ROOT):
    root = Path(root)
    owners = package_repos(root)
    native = json.loads((root / 'policy' / 'native-lock.json').read_text(encoding='utf-8'))['libraries']
    rows = {row['name']: row for row in native}
    partitions = {}
    for row in native:
        for consumer in row['consumers']:
            partitions.setdefault(consumer_repo(consumer, owners), set()).add(row['name'])
    for repo, providers in SHIM_PROVIDERS.items():
        partitions.setdefault(repo, set()).update(providers)
    for libraries in partitions.values():
        pending = list(libraries)
        while pending:
            for dependency in rows[pending.pop()]['dependencies']:
                if dependency not in libraries:
                    libraries.add(dependency)
                    pending.append(dependency)
    peers = {}
    for name, row in json.loads((root / 'policy' / 'peer-lock.json').read_text(encoding='utf-8'))['peers'].items():
        if not row.get('consumers'):
            raise ValueError(f'policy/peer-lock.json: {name} names no consumers')
        for consumer in row['consumers']:
            peers.setdefault(consumer_repo(consumer, owners), set()).add(name)
    return {'schema': 'flint.lock-partitions/1',
            'note': 'Generated by tools/platform_modules.py --write from policy/native-lock.json, policy/peer-lock.json '
                    'and the packages\' repos: the slice of each lock that each repo carries after the split. Do not edit.',
            'native': {repo: sorted(names) for repo, names in sorted(partitions.items())},
            'peers': {repo: sorted(names) for repo, names in sorted(peers.items())}}


def platform_lock(root=ROOT):
    document = json.loads((Path(root) / 'platform.lock').read_text(encoding='utf-8'))
    if document.get('schema') != 'flint.platform/1':
        raise ValueError('platform.lock: schema must be flint.platform/1')
    return document


def version(entry):
    """A repo's platform version: its tag, else its commit, else `monorepo` while every repo is this checkout."""
    return entry.get('tag') or entry.get('commit') or entry['source']


def bill_of_materials(root=ROOT):
    lock = platform_lock(root)
    release = tomllib.loads((Path(root) / 'policy' / 'platform.toml').read_text(encoding='utf-8'))
    artifacts = {}
    for name, (repo, _) in sorted(package_repos(root).items()):
        artifacts['flint:' + name] = {'repo': repo, 'version': version(lock['repos'][repo])}
    return {'schema': 'flint.bom/1',
            'note': 'Generated by tools/platform_modules.py --write from policy and platform.lock: the coordinated set of '
                    'flint:* artifacts an application builds against, as spring-boot-dependencies. Do not edit.',
            'release': release.get('platform', {}).get('release', release.get('release', '')),
            'artifacts': artifacts}


def problems(root=ROOT):
    found = []
    lock = platform_lock(root)
    repos = set(repo_policy(root)['repos'])
    if set(lock['repos']) != repos:
        found.append(f'platform.lock pins {sorted(lock["repos"])}, policy/repos.json lists {sorted(repos)}')
    for repo, entry in sorted(lock['repos'].items()):
        if entry.get('source') != 'monorepo' and not entry.get('commit'):
            found.append(f'platform.lock: {repo} needs a commit, or source "monorepo" before the split')
    path = Path(root) / 'boot' / 'dependencies' / 'flint-dependencies.json'
    if not found and (not path.is_file() or json.loads(path.read_text(encoding='utf-8')) != bill_of_materials(root)):
        found.append('boot/dependencies/flint-dependencies.json is stale: run python3 tools/platform_modules.py --write')
    partitions = Path(root) / 'policy' / 'lock-partitions.json'
    if (Path(root) / 'policy' / 'native-lock.json').is_file() and (
            not partitions.is_file() or json.loads(partitions.read_text(encoding='utf-8')) != lock_partitions(root)):
        found.append('policy/lock-partitions.json is stale: run python3 tools/platform_modules.py --write')
    return found


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--check', action='store_true')
    group.add_argument('--write', action='store_true')
    arguments = parser.parse_args()
    if arguments.write:
        BOM.parent.mkdir(parents=True, exist_ok=True)
        BOM.write_text(json.dumps(bill_of_materials(), indent=2) + '\n', encoding='utf-8')
        PARTITIONS.write_text(json.dumps(lock_partitions(), indent=2) + '\n', encoding='utf-8')
        print(BOM.relative_to(ROOT), PARTITIONS.relative_to(ROOT))
        return 0
    found = problems()
    for problem in found:
        print('PLATFORM:', problem, file=sys.stderr)
    return 1 if found else 0


if __name__ == '__main__':
    sys.exit(main())
