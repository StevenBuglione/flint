#!/usr/bin/env python3
"""Platform modules (ADR-023 amendment, plan section 7).

A platform module is one repo: a set of flint:* packages that share one tag and resolve by platform version, never
by minimal version selection. `platform.lock` in the flint repo pins every Flint repo; the `flint-dependencies`
bill of materials (boot/dependencies/flint-dependencies.json, as spring-boot-dependencies) pins the coordinated
set of artifacts for applications.

    python3 tools/platform_modules.py --check     # platform.lock covers every repo; the bill of materials is current
    python3 tools/platform_modules.py --write     # regenerate the bill of materials from policy and platform.lock
"""
import argparse
import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
from workspace import package_repos, repo_policy  # noqa: E402

LOCK = ROOT / 'platform.lock'
BOM = ROOT / 'boot' / 'dependencies' / 'flint-dependencies.json'


def platform_lock(root=ROOT):
    document = json.loads((Path(root) / 'platform.lock').read_text(encoding='utf-8'))
    if document.get('schema') != 'flint.platform/1':
        raise ValueError('platform.lock: schema must be flint.platform/1')
    return document


def version(entry):
    """A repo's platform version: its tag, else its commit, else `monorepo` while every repo is this checkout."""
    return entry.get('tag') or entry.get('commit') or entry['source']


def bill_of_materials(root=ROOT):
    lock = platform_lock(root)
    release = tomllib.loads((Path(root) / 'policy' / 'platform.toml').read_text(encoding='utf-8'))
    artifacts = {}
    for name, (repo, _) in sorted(package_repos(root).items()):
        artifacts['flint:' + name] = {'repo': repo, 'version': version(lock['repos'][repo])}
    return {'schema': 'flint.bom/1',
            'note': 'Generated by tools/platform_modules.py --write from policy and platform.lock: the coordinated set of '
                    'flint:* artifacts an application builds against, as spring-boot-dependencies. Do not edit.',
            'release': release.get('platform', {}).get('release', release.get('release', '')),
            'artifacts': artifacts}


def problems(root=ROOT):
    found = []
    lock = platform_lock(root)
    repos = set(repo_policy(root)['repos'])
    if set(lock['repos']) != repos:
        found.append(f'platform.lock pins {sorted(lock["repos"])}, policy/repos.json lists {sorted(repos)}')
    for repo, entry in sorted(lock['repos'].items()):
        if entry.get('source') != 'monorepo' and not entry.get('commit'):
            found.append(f'platform.lock: {repo} needs a commit, or source "monorepo" before the split')
    path = Path(root) / 'boot' / 'dependencies' / 'flint-dependencies.json'
    if not found and (not path.is_file() or json.loads(path.read_text(encoding='utf-8')) != bill_of_materials(root)):
        found.append('boot/dependencies/flint-dependencies.json is stale: run python3 tools/platform_modules.py --write')
    return found


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--check', action='store_true')
    group.add_argument('--write', action='store_true')
    arguments = parser.parse_args()
    if arguments.write:
        BOM.parent.mkdir(parents=True, exist_ok=True)
        BOM.write_text(json.dumps(bill_of_materials(), indent=2) + '\n', encoding='utf-8')
        print(BOM.relative_to(ROOT))
        return 0
    found = problems()
    for problem in found:
        print('PLATFORM:', problem, file=sys.stderr)
    return 1 if found else 0


if __name__ == '__main__':
    sys.exit(main())
