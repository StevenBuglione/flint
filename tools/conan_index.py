#!/usr/bin/env python3
"""Generate Flint's Conan recipe index (native/conan-index) from policy/native-lock.json (ADR-023).

The index is a Conan 2 `local-recipes-index`: recipes/<name>/config.yml and recipes/<name>/all/{conanfile.py,
conandata.yml}. Every recipe downloads exactly the source archive and SHA-256 the lock pins, declares the lock's
licence and dependencies, and builds through the vetted per-library steps of tools/native_build.py (hardening,
provider options and the sanitizer variant included). Each recipe embeds the SHA-256 of native_build.py and refuses a
different one, so a change to the build steps changes every recipe revision and therefore every package ID.

    python3 tools/conan_index.py --write   # regenerate after editing the lock or native_build.py
    python3 tools/conan_index.py --check   # fail when the checked-in index differs
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INDEX = ROOT / 'native' / 'conan-index'
# The providers tools/native_build.py builds for the workspace: its `ci` profile, Wasmtime (which the CI lane adds
# explicitly) and liburing (which every reactor consumer needs on Linux).
PROVIDERS = ('openssl', 'libsodium', 'llhttp', 'nghttp2', 'curl', 'sqlite', 'libpq', 'librdkafka', 'zstd', 'zlib',
             'brotli', 'libarchive', 'utf8proc', 'libyaml', 'sdl3', 'protobuf-c', 'hiredis', 'wasmtime', 'liburing',
             'crypt-blowfish')

RECIPE = '''# Generated by tools/conan_index.py from policy/native-lock.json. Do not edit.
import json
import os
import shutil
import subprocess
from pathlib import Path

from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.files import download

NAME = {name!r}
DEPENDENCIES = {dependencies!r}
BUILD_ENGINE_SHA256 = {engine!r}
TARGETS = {targets!r}


class FlintNative(ConanFile):
    name = NAME
    version = {version!r}
    license = {license!r}
    homepage = {homepage!r}
    description = "Flint native provider " + NAME + ", built by Flint's pinned build steps"
    package_type = "static-library"
    settings = "os", "arch", "compiler", "build_type"
    options = {options!r}
    default_options = {default_options!r}

    def validate(self):
        if self.flint_target() not in TARGETS:
            raise ConanInvalidConfiguration(NAME + " does not support " + self.flint_target())

    def requirements(self):
        for dependency in DEPENDENCIES:
            self.requires(dependency, transitive_headers=True, transitive_libs=True)

    def flint_target(self):
        os_name = str(self.settings.os)
        arch = {{"x86_64": "x86_64", "armv8": "aarch64"}}.get(str(self.settings.arch), str(self.settings.arch))
        if os_name == "Linux":
            return "linux-" + arch + "-" + str(self.settings.get_safe("os.libc") or "glibc")
        return {{"Macos": "macos-arm64", "Windows": "windows-x86_64"}}.get(os_name, os_name)

    def source(self):
        data = self.conan_data["sources"][self.version]
        download(self, data["url"], data["sha256"] + ".tar.gz", sha256=data["sha256"])

    def build(self):
        flint = Path(os.environ["FLINT_HOME"])
        engine = flint / "tools" / "native_build.py"
        actual = __import__("hashlib").sha256(engine.read_bytes()).hexdigest()
        if actual != BUILD_ENGINE_SHA256:
            raise ConanException("tools/native_build.py differs from the build steps this recipe pins; "
                                 "run python3 tools/conan_index.py --write")
        build = Path(self.build_folder)
        prefix = build / "prefix"
        shutil.rmtree(prefix, ignore_errors=True)
        prefix.mkdir()
        for dependency in self.dependencies.host.values():
            shutil.copytree(dependency.package_folder, prefix, symlinks=True, dirs_exist_ok=True,
                            ignore=shutil.ignore_patterns("conaninfo.txt", "conanmanifest.txt",
                                                          "flint-native-package.json"))
        inherited = sorted(p.relative_to(prefix).as_posix() for p in prefix.rglob("*") if not p.is_dir())
        (build / "inherited.json").write_text(json.dumps(inherited))
        sha256 = self.conan_data["sources"][self.version]["sha256"]
        cache = build / "work" / "cache"
        cache.mkdir(parents=True, exist_ok=True)
        shutil.copy2(Path(self.source_folder) / (sha256 + ".tar.gz"), cache / (sha256 + ".tar.gz"))
        argv = ["python3", str(engine), "--library", NAME, "--no-dependencies", "--no-shims",
                "--target", self.flint_target(), "--phase", "build", "--work-dir", str(build / "work"),
                "--prefix", str(prefix), "--jobs", str(os.cpu_count() or 2)]
        if self.options.get_safe("smtp"):
            argv += ["--profile", "ci"]
        if str(self.settings.compiler) == "clang":
            clang = self.conf.get("user.flint:clang", check_type=str)
            argv += ["--cc", clang, "--cxx", clang + "++"]
        if str(self.options.sanitize) != "none":
            argv += ["--sanitize", str(self.options.sanitize)]
        toolchain = self.conf.get("user.flint:cmake_toolchain", check_type=str)
        if toolchain:
            argv += ["--cmake-toolchain", toolchain]
        result = subprocess.run(argv, cwd=build, capture_output=True, text=True)
        (build / "native-build.log").write_text(result.stdout + result.stderr)
        if result.returncode:
            raise ConanException(NAME + " failed to build: " + (result.stderr or result.stdout)[-6000:])

    def package(self):
        build = Path(self.build_folder)
        prefix = build / "prefix"
        package = Path(self.package_folder)
        inherited = set(json.loads((build / "inherited.json").read_text()))
        for path in sorted(prefix.rglob("*")):
            relative = path.relative_to(prefix).as_posix()
            if path.is_dir() or relative in inherited or relative == "flint-native-install.json":
                continue
            target = package / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(path, target, follow_symlinks=False)
        receipt = json.loads((prefix / "flint-native-install.json").read_text())
        record = receipt["libraries"][NAME]
        for item in record.get("archives", []):
            item["path"] = Path(item["path"]).relative_to(prefix).as_posix()
        metadata = record.get("system_link_metadata")
        if metadata and metadata.get("path"):
            source = Path(metadata["path"])
            destination = package / "flint" / (NAME + "-" + source.name)
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, destination)
            metadata["path"] = destination.relative_to(package).as_posix()
        document = {{"schema": 1, "name": NAME, "version": self.version, "record": record}}
        (package / "flint-native-package.json").write_text(json.dumps(document, indent=2, sort_keys=True) + "\\n")

    def package_info(self):
        document = json.loads((Path(self.package_folder) / "flint-native-package.json").read_text())
        archives = [Path(item["path"]) for item in document["record"].get("archives", [])]
        self.cpp_info.includedirs = ["include"]
        self.cpp_info.libdirs = sorted({{archive.parent.as_posix() for archive in archives}}) or ["lib"]
        self.cpp_info.libs = [archive.stem[3:] if archive.stem.startswith("lib") else archive.stem
                              for archive in archives]
        if self.settings.os == "Linux":
            self.cpp_info.system_libs = ["pthread", "dl", "m"]
'''


def lock_rows():
    lock = json.loads((ROOT / 'policy' / 'native-lock.json').read_text())
    return {row['name']: row for row in lock['libraries']}


def homepage(row):
    if 'repo' in row:
        return 'https://github.com/' + row['repo']
    return '/'.join(row['archive_url'].split('/')[:3])


def recipe_files(rows, engine):
    """{relative path: text} of the whole index."""
    files = {'README.md': README}
    for name in PROVIDERS:
        row = rows[name]
        version = row['version']
        options = {'sanitize': ['none', 'address,undefined']}
        defaults = {'sanitize': 'none'}
        if name == 'curl':
            options['smtp'] = [True, False]
            defaults['smtp'] = True
        dependencies = [dep + '/' + rows[dep]['version'] for dep in row['dependencies']]
        files[f'recipes/{name}/config.yml'] = f'versions:\n  "{version}":\n    folder: all\n'
        files[f'recipes/{name}/all/conandata.yml'] = (
            f'# Generated by tools/conan_index.py from policy/native-lock.json. Do not edit.\nsources:\n'
            f'  "{version}":\n    url: "{row["archive_url"]}"\n    sha256: "{row["archive_sha256"]}"\n')
        files[f'recipes/{name}/all/conanfile.py'] = RECIPE.format(
            name=name, version=version, license=row['license_selected'], homepage=homepage(row),
            dependencies=dependencies, engine=engine, targets=sorted(row['targets']), options=options,
            default_options=defaults)
    return files


README = '''# Flint's Conan recipe index

Generated by `python3 tools/conan_index.py --write` from `policy/native-lock.json`; do not edit by hand.

This is a Conan 2 `local-recipes-index`. flint's native resolver registers it as the only remote of its isolated
Conan home, so Conan resolves nothing outside it. Each recipe pins the lock's source archive and SHA-256, licence and
dependencies, and builds through the vetted steps of `tools/native_build.py`, whose SHA-256 every recipe embeds.
See ADR-023 for why the index is checked in.
'''


def index_state():
    """(build engine SHA-256, the index's files as generated, the index's files on disk)."""
    engine = hashlib.sha256((ROOT / 'tools' / 'native_build.py').read_bytes()).hexdigest()
    expected = recipe_files(lock_rows(), engine)
    actual = {p.relative_to(INDEX).as_posix(): p.read_text() for p in INDEX.rglob('*') if p.is_file()} \
        if INDEX.is_dir() else {}
    return engine, expected, actual


def stale_files():
    """The index files that differ from policy/native-lock.json and tools/native_build.py. Every recipe embeds
    native_build.py's SHA-256, so an edit to it without --write makes every native build refuse to run."""
    _, expected, actual = index_state()
    return sorted(set(expected) ^ set(actual) | {k for k in expected if actual.get(k) != expected[k]})


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--write', action='store_true')
    mode.add_argument('--check', action='store_true')
    args = parser.parse_args()
    engine, expected, actual = index_state()
    if args.check:
        stale = stale_files()
        if stale:
            print('native/conan-index differs from policy/native-lock.json and tools/native_build.py: '
                  + ', '.join(stale) + '\nrun: python3 tools/conan_index.py --write', file=sys.stderr)
            return 1
        print(json.dumps({'recipes': len(PROVIDERS), 'files': len(expected), 'build_engine_sha256': engine}))
        return 0
    for relative in set(actual) - set(expected):
        (INDEX / relative).unlink()
    for relative, text in expected.items():
        path = INDEX / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        if actual.get(relative) != text:
            path.write_text(text)
    print(json.dumps({'recipes': len(PROVIDERS), 'files': len(expected), 'build_engine_sha256': engine}))
    return 0


if __name__ == '__main__':
    sys.exit(main())
