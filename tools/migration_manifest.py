#!/usr/bin/env python3
"""Emit and verify deterministic D migration tables and SHA-256 sidecars."""
from __future__ import annotations
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

NAME = re.compile(r"V([0-9]{6,})__([A-Za-z0-9_]+)\.sql\Z")
MODULE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*\Z")
KEYWORDS = set("abstract alias align asm assert auto body bool break byte case cast catch cdouble cent cfloat char class const continue creal dchar debug default delegate delete deprecated do double else enum export extern false final finally float for foreach foreach_reverse function goto idouble if ifloat immutable import in inout int interface invariant ireal is lazy long mixin module new nothrow null out override package pragma private protected public pure real ref return scope shared short static struct super switch synchronized template this throw true try typedef typeid typeof ubyte ucent uint ulong union unittest ushort version void volatile wchar while with __gshared __traits __vector __parameters".split())

class ManifestError(ValueError):
    pass

def dquote(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)

def collect(directory: Path, nontransactional: set[int]) -> list[dict]:
    if not directory.is_dir():
        raise ManifestError(f"migration directory is not a directory: {directory}")
    rows = []
    seen = set()
    total = 0
    for path in sorted(directory.iterdir(), key=lambda p: p.name):
        if path.suffix != ".sql":
            continue
        if path.is_symlink() or not path.is_file():
            raise ManifestError(f"migration must be a regular non-symlink file: {path.name}")
        match = NAME.fullmatch(path.name)
        if match is None:
            raise ManifestError(f"invalid migration filename: {path.name}")
        number = int(match.group(1))
        if number <= 0 or number > 9223372036854775807:
            raise ManifestError(f"version out of signed database range: {path.name}")
        if number in seen:
            raise ManifestError(f"duplicate numeric version: {number}")
        seen.add(number)
        data = path.read_bytes()
        if not data or not data.strip() or len(data) > 1048576:
            raise ManifestError(f"migration is empty or exceeds 1048576 bytes: {path.name}")
        if b"\0" in data:
            raise ManifestError(f"NUL byte in SQL: {path.name}")
        try:
            data.decode("utf-8")
        except UnicodeDecodeError as exc:
            raise ManifestError(f"SQL is not UTF-8: {path.name}") from exc
        total += len(data)
        if total > 67108864:
            raise ManifestError("migration inputs exceed 67108864 bytes")
        rows.append({
            "version": number,
            "file": path.name,
            "description": match.group(2).replace("_", " "),
            "size_bytes": len(data),
            "sha256": hashlib.sha256(data).hexdigest(),
            "transactional": number not in nontransactional,
        })
    if not rows:
        raise ManifestError("no migrations found")
    unknown = nontransactional - seen
    if unknown:
        raise ManifestError("nontransactional versions absent: " + ", ".join(map(str, sorted(unknown))))
    return sorted(rows, key=lambda row: row["version"])

def render(rows: list[dict], module: str) -> str:
    if not MODULE.fullmatch(module) or any(s in KEYWORDS for s in module.split(".")):
        raise ManifestError(f"invalid D module name: {module}")
    lines = [
        "// Generated by tools/migration_manifest.py; regenerate, do not hand edit.",
        f"module {module};",
        "import flint.migrate : Migration;",
        "",
        "enum Migration[] migrations = [",
    ]
    for row in rows:
        digest = ", ".join(f"ubyte(0x{row['sha256'][i:i+2]})" for i in range(0,64,2))
        lines += [
            f"    Migration({row['version']}UL, {dquote(row['description'])},",
            f"        import({dquote(row['file'])}),",
            f"        [{digest}], {'true' if row['transactional'] else 'false'}),",
        ]
    lines += ["];", ""]
    return "\n".join(lines)

def outputs(directory: Path, output: Path, module: str, nontransactional: set[int]) -> dict[Path, bytes]:
    rows = collect(directory, nontransactional)
    emitted = {
        output: render(rows, module).encode(),
        output.with_suffix(".json"): (json.dumps({"schema":1,"module":module,"migrations":rows},indent=2,sort_keys=True)+"\n").encode(),
    }
    for row in rows:
        emitted[directory/(row["file"]+".sha256")] = (row["sha256"]+"  "+row["file"]+"\n").encode()
    if len(emitted) != len(rows)+2:
        raise ManifestError("output path collides with an input sidecar")
    sql_paths = {p.resolve() for p in directory.glob("*.sql")}
    if any(p.resolve() in sql_paths for p in emitted):
        raise ManifestError("output would overwrite a SQL input")
    return emitted

def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--input", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--module", required=True)
    p.add_argument("--nontransactional", action="append", type=int, default=[])
    p.add_argument("--check", action="store_true")
    a=p.parse_args(argv)
    try:
        values=outputs(a.input,a.output,a.module,set(a.nontransactional))
        if a.check:
            stale=[str(path) for path,data in values.items() if not path.is_file() or path.read_bytes()!=data]
            if stale:
                print("stale migration artifacts:\n" + "\n".join(stale),file=sys.stderr)
                return 1
        else:
            for path,data in values.items():
                if path.is_symlink():
                    raise ManifestError(f"refusing to overwrite a symlink: {path}")
                path.parent.mkdir(parents=True,exist_ok=True)
                path.write_bytes(data)
        print(json.dumps({"status":"verified" if a.check else "generated","files":len(values)}))
        return 0
    except (ManifestError,OSError) as exc:
        print(str(exc),file=sys.stderr)
        return 2

if __name__=="__main__":
    sys.exit(main())
